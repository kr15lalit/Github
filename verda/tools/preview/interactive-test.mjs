import { createRequire } from 'module';
const require = createRequire('/opt/node22/lib/node_modules/');
const { chromium, devices } = require('playwright');
const B='http://127.0.0.1:8765/', SHOT=process.argv[2];
const browser=await chromium.launch();
const errs=[];
async function run(ctxOpts, tag){
  const ctx=await browser.newContext(ctxOpts); const p=await ctx.newPage();
  p.on('pageerror',e=>errs.push(tag+' '+e.message));
  const log=(...a)=>console.log(tag,...a);
  await p.goto(B+'shop.html');
  await p.locator('a.add_to_cart_button.product_type_simple').first().click();
  log('toast:', await p.locator('.vp-toast').innerText(), '| count', await p.locator('.fc-cart-count').first().innerText());
  await p.goto(B+'product-wood-pressed-coconut-oil.html');
  await p.locator('.single_add_to_cart_button').click();
  log('no size toast:', await p.locator('.vp-toast').innerText());
  await p.selectOption('select[name="attribute_size"]','1 L');
  await p.waitForTimeout(400);
  log('variation price:', (await p.locator('.woocommerce-variation-price').innerText().catch(()=>'-')).trim());
  await p.fill('input.qty','2');
  await p.locator('.single_add_to_cart_button').click();
  log('count after', await p.locator('.fc-cart-count').first().innerText());
  await p.goto(B+'cart.html');
  log('cart:', (await p.locator('.vp-summary').innerText()).replace(/\n/g,' | '));
  await p.locator('.vp-line').first().locator('button[data-d="1"]').click();
  log('after +:', (await p.locator('.vp-summary').innerText()).replace(/\n/g,' | '));
  await p.locator('.vp-line').nth(1).locator('.vp-remove').click();
  log('after remove:', (await p.locator('.vp-summary').innerText()).replace(/\n/g,' | '));
  if(SHOT) await p.screenshot({path:SHOT+tag+'-cart.png',fullPage:true});
  await p.locator('a[href="checkout.html"].vp-wide').click();
  await p.locator('button[type=submit].vp-wide').click();
  log('errors shown:', await p.locator('.vp-err:not([hidden])').count());
  await p.fill('#vp-email','test@example.com'); await p.fill('#vp-phone','9266604099');
  await p.fill('#vp-first','Asha'); await p.fill('#vp-last','Verma'); await p.fill('#vp-address','12 MG Road');
  await p.fill('#vp-city','Ghaziabad'); await p.selectOption('#vp-state','Uttar Pradesh'); await p.fill('#vp-pin','201014');
  if(SHOT) await p.screenshot({path:SHOT+tag+'-checkout.png',fullPage:true});
  await p.locator('button[type=submit].vp-wide').click();
  log('thanks:', (await p.locator('.vp-thanks').innerText()).slice(0,200).replace(/\n/g,' | '));
  log('count after order', await p.locator('.fc-cart-count').first().innerText());
  if(SHOT) await p.screenshot({path:SHOT+tag+'-thanks.png',fullPage:true});
  await p.goto(B+'about-us.html');
  const inp=p.locator('form.fc-header-search input[type=search]');
  if(await inp.isVisible()){
    await inp.fill('ghee');
    log('search ghee:', (await p.locator('.vp-search').innerText()).replace(/\n/g,' | ').slice(0,200));
    await inp.fill('chana dal');
    log('search chana dal:', (await p.locator('.vp-search').innerText()).replace(/\n/g,' | ').slice(0,200));
    await p.locator('.vp-search-item').first().click(); await p.waitForLoadState();
    log('went to', p.url());
  } else log('search box hidden at this width');
  log('header cart href', await p.locator('.fc-action-cart').first().getAttribute('href'));
  await ctx.close();
}
await run({viewport:{width:1366,height:900}},'desktop');
await run({...devices['iPhone 13']},'phone');
// index fragment loads
const p=await browser.newPage(); p.on('pageerror',e=>errs.push('index '+e.message));
await p.goto(B+'index.html'); await p.locator('a.add_to_cart_button.product_type_simple').first().click();
console.log('index count', await p.locator('.fc-cart-count').first().innerText());
console.log('ERRORS', errs);
await browser.close();
